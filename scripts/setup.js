#!/usr/bin/env node

/**
 * Setup script for AngularDashboardTemplate.
 *
 * Run with: node scripts/setup.js
 *
 * This script prompts for project-specific values and updates all files
 * that contain hardcoded template values, making the repo ready to use
 * as a base for a new project.
 */

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');

// ── Helpers ──────────────────────────────────────────────────────────

function read(file) {
  return fs.readFileSync(path.join(ROOT, file), 'utf8');
}

function write(file, content) {
  fs.writeFileSync(path.join(ROOT, file), content, 'utf8');
}

function prompt(question, defaultValue) {
  const readline = require('readline');
  const rl = readline.createInterface({ input: process.stdin, output: process.stdout });
  return new Promise((resolve) => {
    const prompt = `${question} [${defaultValue}]: `;
    rl.question(prompt, (answer) => {
      rl.close();
      resolve(answer.trim() || defaultValue);
    });
  });
}

// ── Main ─────────────────────────────────────────────────────────────

async function main() {
  console.log('\n========================================');
  console.log('  AngularDashboardTemplate Setup');
  console.log('========================================\n');
  console.log('This script will customize the template for your project.');
  console.log('Answer the prompts below (press Enter to accept defaults).\n');

  const projectName = await prompt('Project name (kebab-case, e.g. my-dashboard)', 'my-dashboard');
  const displayName = await prompt('Display name (e.g. My Dashboard App)', 'My Dashboard App');
  const author = await prompt('Author name', 'Your Name');
  const appId = await prompt('Electron app ID (e.g. com.mycompany.dashboard)', 'com.mycompany.mydashboard');
  const dbName = await prompt('RxDB database name', 'mydashboard');
  const defaultTheme = await prompt('Default theme (light / dark / dracula)', 'dracula');
  const sidebarHeader = await prompt('Sidebar header text', 'My Dashboard');
  const footerText = await prompt('Footer author text', author);

  // Validate theme
  const validThemes = ['light', 'dark', 'dracula'];
  if (!validThemes.includes(defaultTheme)) {
    console.error(`\nInvalid theme "${defaultTheme}". Must be one of: ${validThemes.join(', ')}`);
    process.exit(1);
  }

  // Convert project name to camelCase for Angular project name
  const camelName = projectName
    .split('-')
    .map((word) => word.charAt(0).toUpperCase() + word.slice(1))
    .join('');

  const changes = [];

  // ── 1. package.json ────────────────────────────────────────────────
  {
    const pkg = JSON.parse(read('package.json'));
    const oldName = pkg.name;
    pkg.name = projectName;
    pkg.author = author;
    if (!pkg.homepage) pkg.homepage = `https://github.com/${author.toLowerCase()}/${projectName}`;
    write('package.json', JSON.stringify(pkg, null, 2) + '\n');
    changes.push(`package.json: name "${oldName}" → "${projectName}", added author`);
  }

  // ── 2. angular.json ────────────────────────────────────────────────
  {
    let content = read('angular.json');
    const oldProject = 'angulardashboard1';
    content = content.split(oldProject).join(projectName);
    content = content.split('dist/angulardashboard1').join(`dist/${projectName}`);
    write('angular.json', content);
    changes.push(`angular.json: project name "${oldProject}" → "${projectName}"`);
  }

  // ── 3. src/index.html ──────────────────────────────────────────────
  {
    let content = read('src/index.html');
    content = content.replace(
      /<title>.*?<\/title>/,
      `<title>${displayName}</title>`
    );
    write('src/index.html', content);
    changes.push(`src/index.html: title → "${displayName}"`);
  }

  // ── 4. src/app/config/app.config.overrides.ts ──────────────────────
  {
    const overrides = `/**
 * Project-specific configuration overrides.
 *
 * Generated by scripts/setup.js — edit these values to customize
 * the dashboard for your project.
 */

import { PartialAppConfig } from './app.config.model';

export const OVERRIDES: PartialAppConfig = {
  appName: '${projectName.replace(/-/g, ' ').replace(/\\b\\w/g, (c) => c.toUpperCase())}',
  appTitle: '${displayName}',
  author: '${author}',
  defaultTheme: '${defaultTheme}',
  localStorageNamespace: '${projectName}',
  sidebarHeader: '${sidebarHeader}',
  databaseName: '${dbName}',
  electronAppId: '${appId}',
  electronProductName: '${displayName}',
};
`;
    write('src/app/config/app.config.overrides.ts', overrides);
    changes.push('src/app/config/app.config.overrides.ts: populated with your answers');
  }

  // ── 5. main.js ─────────────────────────────────────────────────────
  {
    let content = read('main.js');
    content = content.replace(
      /appId: '.*?'/,
      `appId: '${appId}'`
    );
    content = content.replace(
      /productName: '.*?'/,
      `productName: '${displayName}'`
    );
    content = content.replace(
      /distPath: '.*?'/,
      `distPath: 'dist/${projectName}/browser/index.html'`
    );
    write('main.js', content);
    changes.push('main.js: appId, productName, distPath updated');
  }

  // ── 6. src/environments/environment.ts ─────────────────────────────
  {
    let content = read('src/environments/environment.ts');
    content = content.replace(
      /appTitle: '.*?'/,
      `appTitle: '${displayName}'`
    );
    write('src/environments/environment.ts', content);
    changes.push('src/environments/environment.ts: appTitle updated');
  }

  // ── 7. src/environments/environment.prod.ts ────────────────────────
  {
    let content = read('src/environments/environment.prod.ts');
    content = content.replace(
      /appTitle: '.*?'/,
      `appTitle: '${displayName}'`
    );
    write('src/environments/environment.prod.ts', content);
    changes.push('src/environments/environment.prod.ts: appTitle updated');
  }

  // ── Summary ────────────────────────────────────────────────────────
  console.log('\n========================================');
  console.log('  Setup Complete!');
  console.log('========================================\n');
  console.log('Changes made:');
  changes.forEach((c) => console.log(`  - ${c}`));

  console.log('\nNext steps:');
  console.log(`  1. cd ${ROOT}`);
  console.log('  2. npm install');
  console.log('  3. npm run start');
  console.log('  4. Edit src/app/config/app.config.overrides.ts for further customizations');
  console.log('  5. Update src/assets/ with your app icons');
  console.log('  6. Replace placeholder data in feature components with your own');
  console.log('');
}

main().catch((err) => {
  console.error('Error:', err);
  process.exit(1);
});
